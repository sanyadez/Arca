/**
 * Rebuild src/ui/icons.js — an SVG sprite of the Lucide icons the web UI uses (https://lucide.dev, ISC).
 * Run after changing the list: `bun scripts/build-icons.ts`. Needs network access.
 */
const ICONS = [
  "archive", "layout-grid", "folder-sync", "camera", "activity", "database", "key-round", "life-buoy", "settings",
  "sun", "moon", "monitor", "user", "play", "shield-check", "shield", "rotate-cw", "arrow-right", "folder-search",
  "loader-circle", "x", "clock", "server", "chevron-right", "chevron-left", "chevron-down", "search", "upload",
  "scissors", "history", "pause", "copy", "check", "triangle-alert", "info", "unplug", "eye", "eye-off",
  "external-link", "log-out", "ellipsis", "plus", "folder", "file", "link", "circle-help", "menu", "refresh-cw",
];
const VERSION = "0.469.0";
let out = `// Generated by scripts/build-icons.ts from Lucide ${VERSION} (https://lucide.dev, ISC license). Do not edit.\nexport const SPRITE = \`<svg xmlns="http://www.w3.org/2000/svg" style="display:none">`;
for (const name of ICONS) {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const svg = await res.text();
  const inner = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
  out += `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
}
out += "</svg>`;\n";
await Bun.write(new URL("../src/ui/icons.js", import.meta.url), out);
console.log(`${ICONS.length} icons`);
